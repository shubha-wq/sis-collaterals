import { useCallback, useEffect, useState } from "react";
import { BUILTIN_PHOTOS, findBuiltinPhoto } from "@/assets/catalog";
import { PHOTO_ACCEPT, PhotoUploadError } from "@/assets/uploadPhoto";
import { Button } from "@/design-system/components/Button";
import type { ImageSource } from "@/model/assets";
import type { PhotoFill, WebFraming, WebOutputId } from "@/model/outputs";
import type { LandscapeNeed } from "@/expansion/landscape";
import type { PhotoSettings } from "@/model/project";
import type { BlobStore, PhotoLibrary, PhotoRecord } from "@/persistence/types";
import { requestPersistentStorage } from "@/persistence/storageStatus";
import type { Edit } from "@/state/edits";
import { BlobThumb } from "../BlobThumb";
import { ConfirmDialog } from "../ConfirmDialog";
import { Field, PanelSection } from "../PanelSection";

export function photoSummary(photo: PhotoSettings): string {
  const s = photo.source;
  if (!s) return "No photo";
  if (s.kind === "builtin") return findBuiltinPhoto(s.id)?.label ?? "Library photo";
  return `Your photo · ${s.name}`;
}

const isSelected = (current: ImageSource | null, s: ImageSource) =>
  !!current && current.kind === s.kind && (s.kind === "builtin" ? (current as { id: string }).id === s.id : (current as { blobId: string }).blobId === s.blobId);

interface PhotoSectionProps {
  photo: PhotoSettings;
  edit: (e: Edit) => void;
  library: PhotoLibrary | null;
  blobs: BlobStore | null;
  open: boolean;
  onToggle: () => void;
  /** Website Banner / Listing: framing controls for that output instead of the Instagram ones. */
  web?: { output: WebOutputId; framing: WebFraming; resolved: "crop" | "fit" | null; landscape?: LandscapeNeed | null; onRetry?: () => void; provider?: string };
}

/** The AI landscape's state for a whole-photo website framing. */
function LandscapeStatus({ need, onRetry, provider }: { need: LandscapeNeed; onRetry?: () => void; provider?: string }) {
  if (need.kind !== "needed") return null;
  const st = need.ready ? { state: "ready" as const } : need.status;
  return (
    <div className="landscape-status" role="status" aria-live="polite" data-state={st.state}>
      {st.state === "ready" && <span>Background extended with AI{provider ? ` (${provider})` : ""}. Your photo itself is unchanged.</span>}
      {(st.state === "generating" || st.state === "idle") && <span>Generating landscape image… You can keep editing.</span>}
      {st.state === "failed" && (
        <>
          <span>Failed — {st.message}</span>
          <button type="button" className="chip" onClick={onRetry}>
            Try again
          </button>
        </>
      )}
      {st.state === "unavailable" && <span>AI background expansion isn't set up, so the sides use a soft edge fill. Fill frame avoids it.</span>}
    </div>
  );
}

const FILLS: Array<[PhotoFill, string]> = [["auto", "Auto"], ["crop", "Fill frame"], ["fit", "Whole photo"]];

/** Fill mode, focal point and zoom for one website output. The photo itself is shared. */
function WebFramingControls({ web, edit }: { web: NonNullable<PhotoSectionProps["web"]>; edit: (e: Edit) => void }) {
  const { output, framing, resolved } = web;
  const set = (f: Partial<WebFraming>) => edit({ type: "web-framing", output, ...f });
  const fit = resolved === "fit";
  return (
    <>
      <p className="label">Framing · 1600 × 1000</p>
      <div className="chips">
        {FILLS.map(([k, l]) => (
          <button key={k} type="button" className="chip" aria-pressed={framing.fill === k} onClick={() => set({ fill: k })}>
            {l}
          </button>
        ))}
      </div>
      <p className="field-hint">
        {framing.fill === "auto"
          ? fit
            ? "Auto: shown whole, so no one is cropped out. The empty sides are new background generated by AI around your photo."
            : "Auto: cropped to fill the frame, keeping most of the photo."
          : fit
            ? "The whole photo is shown at its own proportions. The empty sides are new background generated by AI around it."
            : "The photo fills the frame and the overflow is cropped around the focal point."}{" "}
        The photo is never stretched.
      </p>
      {web.landscape && <LandscapeStatus need={web.landscape} onRetry={web.onRetry} provider={web.provider} />}
      <Field label={`${fit ? "Position" : "Focus"} left ↔ right · ${framing.focusX}%`} htmlFor={`field-${output}-x`}>
        <input id={`field-${output}-x`} type="range" min={0} max={100} value={framing.focusX} onChange={(e) => set({ focusX: Number(e.target.value) })} />
      </Field>
      <Field label={`${fit ? "Position" : "Focus"} up ↕ down · ${framing.focusY}%`} htmlFor={`field-${output}-y`}>
        <input id={`field-${output}-y`} type="range" min={0} max={100} value={framing.focusY} onChange={(e) => set({ focusY: Number(e.target.value) })} />
      </Field>
      {!fit && (
        <Field label={`Zoom · ${Math.round(framing.zoom * 100)}%`} htmlFor={`field-${output}-zoom`}>
          <input id={`field-${output}-zoom`} type="range" min={1} max={2.5} step={0.05} value={framing.zoom} onChange={(e) => set({ zoom: Number(e.target.value) })} />
        </Field>
      )}
      <button type="button" className="chip" onClick={() => edit({ type: "reset-web-framing", output })}>
        Reset framing
      </button>
    </>
  );
}

/**
 * One picker: upload, your photos, the SIS library. Picking a photo puts it
 * on the canvas straight away; uploads are kept in this browser for next time.
 */
export function PhotoSection({ photo, edit, library, blobs, open, onToggle, web }: PhotoSectionProps) {
  const [mine, setMine] = useState<PhotoRecord[]>([]);
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);
  const [toDelete, setToDelete] = useState<PhotoRecord | null>(null);
  const refresh = useCallback(async () => setMine(library ? await library.listPhotos() : []), [library]);
  useEffect(() => void refresh(), [refresh]);

  const choose = (source: ImageSource, focus?: { x: number; y: number }) => {
    edit({ type: "photo", source });
    if (focus) edit({ type: "photo-framing", focusX: focus.x, focusY: focus.y });
  };

  const onUpload = async (file: File | undefined) => {
    setError("");
    if (!file || !library) return;
    setBusy(true);
    try {
      const r = await library.addPhoto(file);
      choose({ kind: "upload", blobId: r.blobId, libraryId: r.id, name: r.name });
      void requestPersistentStorage();
      await refresh();
    } catch (e) {
      setError(e instanceof PhotoUploadError ? e.message : "That photo couldn't be added.");
    } finally {
      setBusy(false);
    }
  };

  return (
    <PanelSection title="Photo" summary={photoSummary(photo)} open={open} onToggle={onToggle}>
      <label className="upload">
        <span>{busy ? "Adding photo…" : "+ Upload a photo"}</span>
        <input id="field-photo-upload" type="file" accept={PHOTO_ACCEPT} aria-label="Upload a photo" disabled={busy} onChange={(e) => { void onUpload(e.target.files?.[0]); e.target.value = ""; }} />
      </label>
      {error && <p className="field-error">{error}</p>}

      {photo.source && web && (
        <>
          <WebFramingControls web={web} edit={edit} />
          <Button variant="ghost" size="sm" onClick={() => edit({ type: "photo", source: null })}>
            Remove photo
          </Button>
        </>
      )}

      {photo.source && !web && (
        <>
          <Field label={`Left ↔ right · ${photo.focusX}%`} htmlFor="field-photo-x">
            <input id="field-photo-x" type="range" min={0} max={100} value={photo.focusX} onChange={(e) => edit({ type: "photo-framing", focusX: Number(e.target.value) })} />
          </Field>
          <Field label={`Up ↕ down · ${photo.focusY}%`} htmlFor="field-photo-y">
            <input id="field-photo-y" type="range" min={0} max={100} value={photo.focusY} onChange={(e) => edit({ type: "photo-framing", focusY: Number(e.target.value) })} />
          </Field>
          <Field label={`Zoom · ${Math.round(photo.zoom * 100)}%`} htmlFor="field-photo-zoom">
            <input id="field-photo-zoom" type="range" min={1} max={2.5} step={0.05} value={photo.zoom} onChange={(e) => edit({ type: "photo-framing", zoom: Number(e.target.value) })} />
          </Field>
          <Button variant="ghost" size="sm" onClick={() => edit({ type: "photo", source: null })}>
            Remove photo
          </Button>
        </>
      )}

      {mine.length > 0 && blobs && (
        <>
          <p className="label">Your photos</p>
          <div className="photo-grid">
            {mine.map((r) => {
              const source: ImageSource = { kind: "upload", blobId: r.blobId, libraryId: r.id, name: r.name };
              return (
                <div key={r.id} className="photo-tile-wrap">
                  <button type="button" className="photo-tile" aria-pressed={isSelected(photo.source, source)} title={r.name} onClick={() => choose(source)}>
                    <BlobThumb blobId={r.thumbnailBlobId} blobs={blobs} alt={r.name} />
                  </button>
                  <button type="button" className="tile-delete" aria-label={`Delete ${r.name} from your photos`} title="Delete from your photos" onClick={() => setToDelete(r)}>
                    ×
                  </button>
                </div>
              );
            })}
          </div>
        </>
      )}

      <p className="label">SIS library</p>
      <div className="photo-grid">
        {BUILTIN_PHOTOS.map((p) => {
          const source: ImageSource = { kind: "builtin", id: p.id };
          return (
            <button key={p.id} type="button" className="photo-tile" aria-pressed={isSelected(photo.source, source)} title={p.label} onClick={() => choose(source, { x: p.focusX, y: p.focusY })}>
              <img src={p.thumbUrl} alt={p.label} loading="lazy" decoding="async" />
            </button>
          );
        })}
      </div>
      <p className="field-hint">Photos you upload are kept in this browser, so you can reuse them in other creatives. One photo is used for every output; changing it updates them all.</p>

      {toDelete && (
        <ConfirmDialog
          title={`Delete “${toDelete.name}”?`}
          body="It's removed from your photos in this browser. Creatives that already use it keep it."
          confirmLabel="Delete photo"
          onCancel={() => setToDelete(null)}
          onConfirm={() => {
            const id = toDelete.id;
            setToDelete(null);
            void library?.deletePhoto(id).then(refresh);
          }}
        />
      )}
    </PanelSection>
  );
}
